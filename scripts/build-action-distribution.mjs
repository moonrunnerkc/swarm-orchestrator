#!/usr/bin/env node
/**
 * Generates the contents of the verifier's product repository, moonrunnerkc/swarm-verify, from
 * this repository: the Action manifest with its source-build step replaced by an install of the
 * published package at one exact version, a package manifest and lockfile naming that version
 * and its integrity, the verifier's README and changelog, an Action reference rendered from the
 * manifest, the example workflows, the pre-commit hook manifest, the license and a record of
 * the source commit. Everything is derived; nothing in that repository is hand-edited, so the
 * Action is a thin client of the published engine and never a second copy of it.
 *
 *   node scripts/build-action-distribution.mjs <published version> <output directory>
 *
 * The lockfile is produced by npm against the registry, so the named version has to be
 * published first. The output directory is replaced.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { preCommitHooksManifest } from "./pre-commit-hooks-manifest.mjs";

const root = resolve(import.meta.dirname, "..");
const packageRoot = join(root, "packages", "swarm-verify");

const sourceBuildBegin = "    # SOURCE-BUILD-BEGIN";
const sourceBuildEnd = "    # SOURCE-BUILD-END\n";

/**
 * The manifest the distribution carries: the same steps as the canonical action.yml beside the
 * package, with the source build replaced by an install of the published package.
 */
export function distributionManifest(canonical, version, sourceCommit) {
  const begin = canonical.indexOf(sourceBuildBegin);
  const end = canonical.indexOf(sourceBuildEnd);
  if (begin === -1 || end === -1) throw new Error("action.yml lacks the source-build markers");
  const installStep = [
    "    # Generated by scripts/build-action-distribution.mjs in moonrunnerkc/swarm-orchestrator at",
    `    # ${sourceCommit}. The lockfile pins swarm-verify@${version} by integrity; nothing else is installed.`,
    "    - name: Install the published verifier",
    "      shell: bash",
    "      env:",
    // Written in two pieces so the manifest holds a workflow expression and this file does not.
    `        SWARM_ACTION_ROOT: $${"{{ github.action_path }}"}`,
    "      run: |",
    '        cd "$SWARM_ACTION_ROOT"',
    "        npm ci --ignore-scripts --omit=dev --no-audit --no-fund",
    '        echo "SWARM_VERIFY_ENTRY=$SWARM_ACTION_ROOT/node_modules/swarm-verify/dist/swarm-verify.js" >> "$GITHUB_ENV"',
    "",
  ].join("\n");
  return canonical.slice(0, begin) + installStep + canonical.slice(end + sourceBuildEnd.length);
}

/**
 * The inputs and outputs the manifest declares, read from its own two-space indentation: a name
 * at four spaces under `inputs:` or `outputs:`, its `description` and `default` at six. The
 * manifest is this repository's own file in a shape its tests hold, so the reader is exact
 * rather than general, and a shape it does not expect is refused rather than guessed at.
 */
export function manifestInterface(canonical) {
  const inputs = [];
  const outputs = [];
  let section = null;
  let current = null;
  for (const line of canonical.split("\n")) {
    if (line === "inputs:" || line === "outputs:") {
      section = line === "inputs:" ? inputs : outputs;
      current = null;
      continue;
    }
    if (section === null) continue;
    if (/^\S/.test(line)) {
      section = null;
      continue;
    }
    const name = /^ {2}([a-z][a-z-]*):$/.exec(line);
    if (name !== null) {
      current = { name: name[1], description: "", default: null };
      section.push(current);
      continue;
    }
    const field = /^ {4}(description|default): (.*)$/.exec(line);
    if (field === null || current === null) continue;
    const [, key, raw] = field;
    const value = /^(['"])(.*)\1$/.exec(raw)?.[2] ?? raw;
    if (key === "description") current.description = value;
    else current.default = value;
  }
  if (inputs.length === 0 || outputs.length === 0) {
    throw new Error("action.yml declares no inputs or no outputs in the shape this reader takes");
  }
  return { inputs, outputs };
}

const cell = (text) => text.replaceAll("|", "\\|");

/** The Action reference: what one run does, every input and output, and the examples. */
export function actionReference(canonical, examples) {
  const { inputs, outputs } = manifestInterface(canonical);
  const inputRows = inputs.map(
    (input) =>
      `| \`${input.name}\` | ${input.default === "" ? "none" : `\`${cell(input.default ?? "")}\``} | ${cell(input.description)} |`,
  );
  const outputRows = outputs.map(
    (output) => `| \`${output.name}\` | ${cell(output.description)} |`,
  );
  const exampleSections = examples.flatMap(({ name, text }) => [
    `### ${name}`,
    "",
    "```yaml",
    text.trimEnd(),
    "```",
    "",
  ]);
  return [
    "# The Swarm Verify GitHub Action",
    "",
    "`moonrunnerkc/swarm-verify@v1` verifies a pull request's head in a network-disabled container,",
    "signs the verdict as a GitHub artifact attestation, and posts one comment bound to the head.",
    "It is a thin client of the published `swarm-verify` package: three steps of the same binary,",
    "`action verify`, `action comment` and `action retain`, with GitHub's own attestation action",
    "between them. The consumer's checkout is not used; the Action fetches the pull request's head",
    "and base by commit id into a checkout it owns.",
    "",
    "`v1` moves only to validated stable releases; `v1.x.y` tags and commit SHAs never move. Where",
    "immutability matters, pin the SHA: `uses: moonrunnerkc/swarm-verify@<sha> # v1.x.y`.",
    "",
    "## What one run does",
    "",
    "1. `verify` reads the event, fetches the exact head and base (or GitHub's test merge, under",
    "   `target: merge`), runs `swarm-verify ci --branch <head> --base <base>` with candidate",
    "   commands behind `--isolation docker:<image> --require-isolation`, and writes `report.json`",
    "   (`swarm.ci.v1`), `summary.md`, the evidence bundle with its own verifier, and",
    "   `verdict.json`: the canonical `swarm-verify.verdict.v1` document binding repository, pull",
    "   request, head, base, tree, patch digest, verifier version, policy, run identity, the digests",
    "   of the report and the bundle's chain head, and the decision.",
    "2. `actions/attest` signs the verdict document with predicate type",
    "   `https://github.com/moonrunnerkc/swarm-verify/verdict/v1`, through the workflow's OIDC",
    "   identity; no key is managed anywhere. It needs `id-token: write`, `attestations: write`",
    "   and `artifact-metadata: write`.",
    "3. `comment` posts one comment on the pull request and updates it in place on reruns. The",
    "   comment is bound to the head it describes; a run for an older head finds a newer one and",
    "   posts nothing, reporting `stale-head`. Needs `pull-requests: write`.",
    "4. `retain` copies the report, summary, verdict, attestation bundle and evidence bundle",
    "   within bounds (32 MB, 8 MB per file, 4096 files), uploaded as one artifact.",
    "5. The final step returns the verification status: 0 for verified or a regression-only pass,",
    "   1 for not verified (or a regression-only pass under `require-task: true`), 4 for an",
    "   incomplete, refused or head-changed run. Attestation and comment status are separate",
    "   outputs; a failed signature or publication is never reported as a delivered signed comment.",
    "",
    "A regression pass says nothing broke. Only a requirement contract can say the work was done,",
    "and the comment says which of the two it is reporting.",
    "",
    "## Inputs",
    "",
    "| Input | Default | What it does |",
    "| --- | --- | --- |",
    ...inputRows,
    "",
    "## Outputs",
    "",
    "| Output | What it holds |",
    "| --- | --- |",
    ...outputRows,
    "",
    "## Verifying a signed verdict from outside the run",
    "",
    "`swarm-verify verdict` binds the document to the report, summary and bundle beside it by",
    "digest, then hands the signer question to GitHub's own attestation verifier against Sigstore's",
    "public trust root; it never reimplements that check, and without `gh` it prints the exact",
    "command and leaves the signer unverified:",
    "",
    "```sh",
    "swarm-verify verdict retained/verdict.json --repo OWNER/REPO \\",
    "  --signer-workflow OWNER/REPO/.github/workflows/swarm-verify.yml",
    "```",
    "",
    "Exit 0 needs both: evidence bound and signer trusted. A verdict signed by a workflow at",
    "another path or in another repository is refused by identity, whatever its contents say.",
    "",
    "## Forks and Dependabot",
    "",
    "Fork and Dependabot pull requests run under a read-only token with no OIDC identity, so on a",
    "plain `pull_request` run their comment and signature report `unavailable` while the",
    "verification and the artifact still happen. The supported route is the `pull_request_target`",
    "workflow below, whose definition comes from the base branch and under which the Action",
    "refuses to run candidate code anywhere but inside docker isolation. Candidate code never sees",
    "the job's token, the runner's socket or the evidence directory.",
    "",
    "## Example workflows",
    "",
    ...exampleSections,
  ].join("\n");
}

/** The repository's own section, appended to the package README it otherwise repeats. */
export function distributionReadme(packageReadme, version, sourceCommit) {
  return `${packageReadme.trimEnd()}

## This repository

The product home of Swarm Verify: the GitHub Action, [the Action reference](docs/action.md),
[the example workflows](examples), [the changelog](CHANGELOG.md) and the releases. The Action
manifest installs the published \`swarm-verify\` package at \`${version}\`, pinned by integrity
in the lockfile, and nothing else. Every file here is generated from
[moonrunnerkc/swarm-orchestrator](https://github.com/moonrunnerkc/swarm-orchestrator) at
\`${sourceCommit}\` by \`scripts/build-action-distribution.mjs\`; the record of that is
[SOURCE.json](SOURCE.json).
`;
}

/** Every file the distribution holds that needs no registry, as path to text. */
export function distributionFiles({
  canonical,
  packageReadme,
  changelog,
  license,
  examples,
  version,
  sourceCommit,
}) {
  return {
    "action.yml": distributionManifest(canonical, version, sourceCommit),
    "README.md": distributionReadme(packageReadme, version, sourceCommit),
    "CHANGELOG.md": changelog,
    "docs/action.md": actionReference(canonical, examples),
    ...Object.fromEntries(examples.map(({ name, text }) => [`examples/${name}`, text])),
    LICENSE: license,
    ".gitignore": "node_modules/\n",
    ".pre-commit-hooks.yaml": preCommitHooksManifest(version),
    "package.json": `${JSON.stringify(
      {
        name: "swarm-verify-action",
        version,
        private: true,
        description: `The Swarm Verify GitHub Action: installs swarm-verify@${version} and runs its action steps.`,
        license: "ISC",
        dependencies: { "swarm-verify": version },
      },
      null,
      2,
    )}\n`,
  };
}

/**
 * The links a README makes into the distribution itself, so a generated page cannot point at a
 * file the generator does not write.
 */
export function distributionLinks(readme) {
  const found = new Set();
  const pattern =
    /https:\/\/github\.com\/moonrunnerkc\/swarm-verify\/blob\/main\/([^)\s#]+)|\]\(((?:docs|examples)\/[^)\s#]+|CHANGELOG\.md|SOURCE\.json)\)/g;
  for (const match of readme.matchAll(pattern)) {
    found.add(match[1] ?? match[2]);
  }
  return [...found].sort();
}

function build(version, output) {
  const destination = resolve(output);
  const sourceCommit = execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: root,
    encoding: "utf8",
  }).trim();
  const examplesRoot = join(root, "docs", "examples");
  const examples = readdirSync(examplesRoot)
    .filter((name) => name.endsWith(".yml"))
    .sort()
    .map((name) => ({ name, text: readFileSync(join(examplesRoot, name), "utf8") }));
  const files = distributionFiles({
    canonical: readFileSync(join(packageRoot, "action.yml"), "utf8"),
    packageReadme: readFileSync(join(packageRoot, "README.md"), "utf8"),
    changelog: readFileSync(join(packageRoot, "CHANGELOG.md"), "utf8"),
    license: readFileSync(join(root, "LICENSE"), "utf8"),
    examples,
    version,
    sourceCommit,
  });
  const missing = distributionLinks(files["README.md"]).filter(
    (path) => !(path in files) && !(path === "examples" || path === "SOURCE.json"),
  );
  if (missing.length > 0) {
    throw new Error(
      `the README links to files the distribution does not hold: ${missing.join(", ")}`,
    );
  }

  rmSync(destination, { recursive: true, force: true });
  mkdirSync(destination, { recursive: true });
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(join(destination, path, ".."), { recursive: true });
    writeFileSync(join(destination, path), text);
  }

  execFileSync(
    "npm",
    ["install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund"],
    { cwd: destination, stdio: "inherit" },
  );
  const lock = JSON.parse(readFileSync(join(destination, "package-lock.json"), "utf8"));
  const pinned = lock.packages?.["node_modules/swarm-verify"];
  if (pinned?.version !== version || typeof pinned?.integrity !== "string")
    throw new Error(`the lockfile does not pin swarm-verify@${version} with an integrity hash`);

  writeFileSync(
    join(destination, "SOURCE.json"),
    `${JSON.stringify(
      {
        repository: "moonrunnerkc/swarm-orchestrator",
        commit: sourceCommit,
        package: "swarm-verify",
        version,
        integrity: pinned.integrity,
      },
      null,
      2,
    )}\n`,
  );
  console.log(
    `distribution for swarm-verify@${version} written to ${destination} (integrity ${pinned.integrity})`,
  );
}

// Importable for its test without touching the registry, run for its effect from the command line.
if (process.argv[1] === import.meta.filename) {
  const [version, output] = process.argv.slice(2);
  if (!version || !output) {
    console.error("usage: build-action-distribution.mjs <published version> <output directory>");
    process.exit(2);
  }
  if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
    console.error(`not a version: ${version}`);
    process.exit(2);
  }
  build(version, output);
}
