#!/usr/bin/env node
/**
 * Generates the contents of the Action distribution repository, moonrunnerkc/swarm-verify,
 * from this repository: the Action manifest with its source-build step replaced by an install
 * of the published package at one exact version, a package manifest and lockfile naming that
 * version and its integrity, the license, and a README. Everything is derived; nothing in the
 * distribution repository is hand-edited, so the Action is a thin client of the published
 * engine and never a second copy of it.
 *
 *   node scripts/build-action-distribution.mjs <published version> <output directory>
 *
 * The lockfile is produced by npm against the registry, so the named version has to be
 * published first. The output directory is replaced.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const [version, output] = process.argv.slice(2);
if (!version || !output) {
  console.error("usage: build-action-distribution.mjs <published version> <output directory>");
  process.exit(2);
}
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`not a version: ${version}`);
  process.exit(2);
}
const root = resolve(import.meta.dirname, "..");
const destination = resolve(output);
const sourceCommit = execFileSync("git", ["rev-parse", "HEAD"], {
  cwd: root,
  encoding: "utf8",
}).trim();

rmSync(destination, { recursive: true, force: true });
mkdirSync(destination, { recursive: true });

// The manifest: the same steps as the canonical action.yml, with the source build replaced.
const canonical = readFileSync(join(root, "action.yml"), "utf8");
const begin = canonical.indexOf("    # SOURCE-BUILD-BEGIN");
const end = canonical.indexOf("    # SOURCE-BUILD-END\n");
if (begin === -1 || end === -1) throw new Error("action.yml lacks the source-build markers");
const installStep = [
  "    # Generated by scripts/build-action-distribution.mjs in moonrunnerkc/swarm-orchestrator at",
  `    # ${sourceCommit}. The lockfile pins swarm-verify@${version} by integrity; nothing else is installed.`,
  "    - name: Install the published verifier",
  "      shell: bash",
  "      env:",
  // Written in two pieces so the manifest holds a workflow expression and this file does not.
  `        SWARM_ACTION_ROOT: $${"{{ github.action_path }}"}`,
  "      run: |",
  '        cd "$SWARM_ACTION_ROOT"',
  "        npm ci --ignore-scripts --omit=dev --no-audit --no-fund",
  '        echo "SWARM_VERIFY_ENTRY=$SWARM_ACTION_ROOT/node_modules/swarm-verify/dist/swarm-verify.js" >> "$GITHUB_ENV"',
  "",
].join("\n");
const manifest =
  canonical.slice(0, begin) +
  installStep +
  canonical.slice(end + "    # SOURCE-BUILD-END\n".length);
writeFileSync(join(destination, "action.yml"), manifest);

writeFileSync(
  join(destination, "package.json"),
  `${JSON.stringify(
    {
      name: "swarm-verify-action",
      version,
      private: true,
      description: `The swarm-verify GitHub Action: installs swarm-verify@${version} and runs its action steps.`,
      license: "ISC",
      dependencies: { "swarm-verify": version },
    },
    null,
    2,
  )}\n`,
);
execFileSync(
  "npm",
  ["install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund"],
  {
    cwd: destination,
    stdio: "inherit",
  },
);
const lock = JSON.parse(readFileSync(join(destination, "package-lock.json"), "utf8"));
const pinned = lock.packages?.["node_modules/swarm-verify"];
if (pinned?.version !== version || typeof pinned?.integrity !== "string")
  throw new Error(`the lockfile does not pin swarm-verify@${version} with an integrity hash`);

writeFileSync(join(destination, "LICENSE"), readFileSync(join(root, "LICENSE")));
writeFileSync(join(destination, ".gitignore"), "node_modules/\n");
writeFileSync(
  join(destination, "README.md"),
  `# swarm-verify GitHub Action

Independently verify what an AI-written pull request actually ran, in a network-disabled
container, and post one signed comment bound to the exact head. This repository holds only
the Action manifest and a lockfile pinning the published \`swarm-verify\` package at
\`${version}\`; the implementation is
[moonrunnerkc/swarm-orchestrator](https://github.com/moonrunnerkc/swarm-orchestrator) at
\`${sourceCommit}\`, under \`src/action/\`.

\`\`\`yaml
name: swarm-verify
on:
  pull_request:
permissions:
  contents: read
  pull-requests: write
  id-token: write
  attestations: write
  artifact-metadata: write
jobs:
  verify:
    runs-on: ubuntu-latest
    steps:
      - uses: moonrunnerkc/swarm-verify@v1
\`\`\`

Pin by full commit SHA where immutability matters. Inputs, outputs, the fork route and how to
verify a signed verdict with \`gh attestation verify\` are documented in
[the broad-use guide](https://github.com/moonrunnerkc/swarm-orchestrator/blob/v13-main/docs/broad-use.md#github-action).

A regression pass says nothing broke. Only a requirement contract can say the work was done,
and the comment says which of the two it is reporting.
`,
);
// The pre-commit framework installs this repository as a node package, which is the pinned
// verifier and nothing else, and runs the staged-tree verification from it.
writeFileSync(
  join(destination, ".pre-commit-hooks.yaml"),
  [
    "- id: swarm-verify",
    "  name: swarm-verify (staged tree)",
    "  description: Verify the staged tree with swarm-verify before the commit; the working tree is never touched.",
    "  entry: swarm-verify pre-commit",
    "  language: node",
    "  pass_filenames: false",
    "  always_run: true",
    "  stages: [pre-commit]",
    "",
  ].join("\n"),
);
writeFileSync(
  join(destination, "SOURCE.json"),
  `${JSON.stringify({ repository: "moonrunnerkc/swarm-orchestrator", commit: sourceCommit, package: "swarm-verify", version, integrity: pinned.integrity }, null, 2)}\n`,
);
console.log(
  `distribution for swarm-verify@${version} written to ${destination} (integrity ${pinned.integrity})`,
);
